"""A CDN's or firewall's "access denied" page is no content: the site refused this server.
nbcnewyork.com's Akamai page counted as a successful retrieval."""

from scrapemm.common.exceptions import AccessBlockedError
from scrapemm.common.scraping_response import ScrapedContent
from scrapemm.server.engine import _access_denied_page, _classify

AKAMAI = ("Access Denied\n\n# Access Denied\n\nYou don't have permission to access "
          "\"http://www.nbcnewyork.com/new-york-city/mta-subway-lirr-fare-hikes/6438701/\" on this "
          "server.\n\nReference #18.d4b31402.1791820969.e28c33\n\n"
          "https://errors.edgesuite.net/18.d4b31402.1791820969.e28c33")


def test_akamais_page_is_recognised_and_fails_the_method():
    assert _access_denied_page(ScrapedContent(markdown=AKAMAI)) == "Akamai"
    status, error = _classify("https://www.nbcnewyork.com/x", "browser",
                              ScrapedContent(markdown=AKAMAI), "markdown")
    assert status == "error" and isinstance(error, AccessBlockedError)
    assert "access denied" in str(error)  # Which makes it a refusal of this server's address


def test_other_cdns_and_bare_403_pages():
    pages = {
        "Imperva": "Request unsuccessful. Incapsula incident ID: 123000450123456789-12345678901234567",
        "Sucuri": "Access Denied - Sucuri Website Firewall\n\nBlock reason: Access from your area has been disabled.",
        "CloudFront": "403 ERROR\n\nThe request could not be satisfied.\n\nGenerated by cloudfront (CloudFront)",
        "Cloudflare": "Sorry, you have been blocked\n\nYou are unable to access example.com\n\nCloudflare Ray ID: 8a1b2c3d",
        "the server": "403 Forbidden\n\nnginx",
    }
    for who, text in pages.items():
        assert _access_denied_page(ScrapedContent(markdown=text)) == who, who


def test_articles_and_ordinary_pages_are_left_alone():
    article = ("# Why sites say 403 Forbidden\n\nWhen you see \"You don't have permission to access\" "
               "and a Reference # from Akamai, ... " + "More explanation. " * 200)
    assert _access_denied_page(ScrapedContent(markdown=article)) is None
    assert _access_denied_page(ScrapedContent(markdown="MTA fare hikes take effect Sunday.")) is None
